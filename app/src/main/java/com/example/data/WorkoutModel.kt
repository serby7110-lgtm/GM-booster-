enum class WorkoutCategory(
    val arabicTitle: String,
    val englishTitle: String,
    val indonesianTitle: String,
    val iconName: String
) {
    CHEST("الصدر", "Chest", "Dada", "fitness_center"),
    BACK("الظهر", "Back", "Punggung", "accessibility_new"),
    LEGS("الأرجل والسمانة", "Legs & Calves", "Kaki & Betis", "directions_run"),
    SHOULDERS_ARMS("الأكتاف والذراعين", "Shoulders & Arms", "Bahu & Lengan", "sports_gymnastics"),
    CORE_ABS("البطن والكور", "Core & Abs", "Perut & Inti", "self_improvement"),
    FULL_BODY("كامل الجسم", "Full Body", "Seluruh Tubuh", "flash_on"),
    HIIT_CARDIO("كارديو وحرق دهون", "Cardio & HIIT", "Kardio & HIIT", "local_fire_department");

    fun getLocalizedTitle(lang: AppLanguage): String = when (lang) {
        AppLanguage.ARABIC -> arabicTitle
        AppLanguage.ENGLISH -> englishTitle
        AppLanguage.INDONESIAN -> indonesianTitle
    }
}

enum class WorkoutEnvironment(
    val arabicTitle: String,
    val englishTitle: String,
    val indonesianTitle: String
) {
    HOME("منزل (Home)", "Home", "Rumah"),
    GYM("صالة رياضية (Gym)", "Gym", "Gym"),
    BOTH("المنزل أو الصالة", "Home & Gym", "Rumah & Gym");

    fun getLocalizedTitle(lang: AppLanguage): String = when (lang) {
        AppLanguage.ARABIC -> arabicTitle
        AppLanguage.ENGLISH -> englishTitle
        AppLanguage.INDONESIAN -> indonesianTitle
    }
}

